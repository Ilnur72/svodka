import { useState } from "react";
import type { PanelProps } from "../types";
import { SegmentSwitch } from "../components/SegmentSwitch";
import { H2Panel } from "./H2Panel";
import { GasPanel } from "./GasPanel";

/**
 * «Водород ва газ» бўлими — иккита кўриниш, битта таб ичида.
 *
 * ═══ Нега ажратилди ════════════════════════════════════════════════════
 *
 * Иккала кўрсаткич ҳам «сарф, м³» бўлса ҳам, улар **бошқа-бошқа манбадан**
 * келади ва бир-бири билан таққосланмайди:
 *
 *  · **Водород** — ишлаб чиқариш ҳисоботидан (`production-report`), цехлар
 *    кесимида, ойлик режа-факт мантиғи билан.
 *  · **Газ** — ҳисоблагич ўлчовларидан (АСУПГ интеграцияси), ўлчов
 *    нуқталари кесимида, кунлик ўлчов қаторлари билан.
 *
 * Уларни битта экранга қўйиш «жами сарф» деган умумий сон бор деган нотўғри
 * таассурот берарди. Шунинг учун ҳар кўриниш ўз манбаси ва ўз кесимида
 * қолади, қўшилмайди.
 *
 * ═══ Нега «Табиий газ сарфи» плиткаси Водороддан олиб ташланди ═════════
 *
 * У `production-report` дан келарди ва ҳисоблагич кўрсаткичидан фарқ
 * қиларди. Битта нарса ҳақида икки жойда икки хил сон туриши — раҳбар учун
 * энг ёмон ҳолат, шунинг учун газ рақами энди фақат «Газ» кўринишида.
 *
 * ═══ Ҳолат нега `useState` ══════════════════════════════════════════════
 *
 * Манзил сатридаги `#` асосий табларга тегишли (`useHashTab`). Ички
 * кўриниш танлови унга ёзилмайди — `ObzorPanel` даги нақш билан бир хил.
 */

const VIEWS = [
  {
    id: "h2",
    label: "Водород",
    hint: "Ишлаб чиқариш ҳисоботидан: цехлар кесимида водород сарфи, кунлик динамика ва истеъмол тузилиши.",
  },
  {
    id: "gas",
    label: "Газ",
    // Экранда ташқи тизимнинг номи (АСУПГ) кўрсатилмайди — раҳбар учун
    // маъноси йўқ; манба «ҳисоблагич» деб аталади.
    hint: "Газ ҳисоблагичларидан: ўлчов нуқталари бўйича табиий газ сарфи, кунлик ўлчов қатори ва улуш.",
  },
] as const;

type ViewId = (typeof VIEWS)[number]["id"];

export function H2GasPanel(props: PanelProps) {
  const [view, setView] = useState<ViewId>("h2");

  return (
    <>
      <div className="mb-4 flex flex-wrap items-start justify-between gap-x-5 gap-y-2.5">
        <SegmentSwitch
          label="Водород ва газ кўриниши"
          options={VIEWS}
          value={view}
          onChange={setView}
        />
      </div>

      {/* Иккала панел ҳам ўз сўровини ўзи юборади. Кўриниш алмашганда
          иккинчиси биринчи марта юкланади — бу атайлаб: фойдаланувчи
          очмаган кўриниш учун сўров юборилмайди. */}
      {view === "h2" && <H2Panel {...props} />}
      {view === "gas" && <GasPanel {...props} />}
    </>
  );
}
