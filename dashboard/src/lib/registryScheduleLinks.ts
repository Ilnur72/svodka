const BY_REGISTRY_KEY: ReadonlyMap<string, RegistryScheduleLink> = new Map(
  REGISTRY_SCHEDULE_LINKS.map((l) => [l.registryKey, l]),
);

/**
 * Реестр лойиҳасининг графиги. Мослик — `key` нинг ТЎЛИҚ тенглиги;
 * жадвалда йўқ лойиҳа учун `undefined` (ойнада таб чизилмайди).
 */
export const registryScheduleLink = (registryKey: string): RegistryScheduleLink | undefined =>
  BY_REGISTRY_KEY.get(registryKey);

/** Огоҳлантириш бир марта ёзилади — ҳар очилишда такрорланмасин. */
let warned = false;

/**
 * Жадвалдаги реестр калити юкланган лойиҳалар орасида топилмаса — dev
 * режимида консолга ёзилади. Акс ҳолда таб жимгина йўқоларди ва бу
 * «бу лойиҳада график йўқ» ҳолатидан фарқ қилмасди.
 *
 * Прод build'да умуман ишламайди: `import.meta.env.DEV` ёлғон бўлганда
 * функция биринчи қаторда қайтади.
 */
export function warnLostRegistryScheduleLinks(loadedKeys: Iterable<string>): void {
  if (!import.meta.env.DEV || warned) return;
  warned = true;
  const have = new Set(loadedKeys);
  const lost = REGISTRY_SCHEDULE_LINKS.filter((l) => !have.has(l.registryKey));
  if (lost.length === 0) return;
  console.warn(
    "[registryScheduleLinks] реестрда топилмаган калитлар — график таби чизилмайди:",
    lost.map((l) => `id ${l.registryId} · ${l.registryKey} → ${l.scheduleKey}`),
  );
}
