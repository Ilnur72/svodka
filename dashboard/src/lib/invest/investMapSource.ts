/** Ёрлиқ маркернинг қайси ёнида турадиган томони. */
export type InvestLabelSide = "left" | "right";

export interface InvestMapPoint {
  /** Шарқий узунлик, градус (WGS 84). */
  lon: number;
  /** Шимолий кенглик, градус (WGS 84). */
  lat: number;
  /** Ёрлиқ маркернинг қайси ёнида чизилади. */
  label: InvestLabelSide;
  /** Ёрлиқнинг вертикал силжиши, экран пикселида. Манфий — юқорига. */
  labelDy: number;
  /**
   * Маркер расмининг экрандаги силжиши, пикселда: `[x, y]`, мусбат y —
   * пастга. Геодезик лангарга ТЕГМАЙДИ — у ҳақиқий координатада қолади.
   * `[0, 0]` бўлса маркер айнан ўз нуқтасида чизилади.
   */
  offset: [number, number];
  /**
   * Маркер силжитилган бўлса — сабаби ва миқдори. `null` бўлса силжиш йўқ.
   */
  nudge: string | null;
}

