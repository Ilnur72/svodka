import { useState } from "react";

/**
 * «Лойиҳа майдони» блокидаги сурат майдони.
 *
 * ═══ Расм бор-йўқлиги фақат браузерда маълум ════════════════════════════
 *
 * Файл `public/` да туради — у бандлга кирмайди, шунинг учун build
 * пайтида ҳам, рендер пайтида ҳам «бор ёки йўқ» деб текшириб бўлмайди.
 * Ягона ишончли сигнал — браузернинг ўзи: `onLoad` ёки `onError`.
 *
 * Учта ҳолат бор ва учаласи бошқача кўринади:
 *   - `load` — жавоб ҳали келмаган: жойни нейтрал майдон эгаллаб туради,
 *     расм эса шаффоф. Айнан шу сабабли синиқ расм иконкаси ҳам, `alt`
 *     матни ҳам экранга чиқмайди;
 *   - `ok`   — расм кўринади;
 *   - `fail` — расм умуман чизилмайди, ўрнида хотиржам плашка туради.
 *
 * `aspect-[16/10]` — расмнинг энг кичик баландлиги, қатъий ўлчов эмас.
 *
 * ═══ Нега алоҳида компонент ═════════════════════════════════════════════
 *
 * Юқоридаги учта ҳолат иккита бўлимда бир хил керак: «Инвестиция
 * лойиҳалари» паспортида ва «Лойиҳалар реестри» тафсилотида. Иккинчи
 * нусхаси ёзилса, биттасида `onError` унутилиши билан ўша ерда синиқ расм
 * иконкаси пайдо бўларди. Блокнинг қолган қисми (сарлавҳа, кўрсаткичлар,
 * изоҳ) ҳар бўлимнинг ўзида қолади — улар манбага боғлиқ.
 */
export interface AreaPhotoProps {
  src: string;
  /** Расмнинг матнли муқобили — лойиҳа номи билан. */
  alt: string;
  /**
   * Плашканинг иккинчи қатори — расм йўқлигида нима кўрсатилаётганини
   * айтади. Бўлимга қараб матн бошқача бўлади, шунинг учун чақирувчидан
   * келади.
   */
  note: string;
  /**
   * Устун грид қатори баландлигига чўзилганда ортиқча жойни расм ютсинми.
   *
   * `true` («Инвестиция лойиҳалари» паспорти) — ютади: у ерда уч устун
   * баландлиги яқин ва расм шу блокнинг асосий мазмуни, шунинг учун бўш
   * оралиқ ҳосил қилгандан кўра расмни каттароқ кўрсатган маъқул.
   *
   * `false` («Лойиҳалар реестри» тафсилоти) — ютмайди: у ерда чап устунда
   * тўрттагача карточка туради ва расм 700px дан ошиб кетарди. Реестрда
   * сурат ҲОЗИРЧА умуман йўқ, яъни ўша жой бўм-бўш плашка бўлиб қоларди.
   * Нисбат ўзгармайди — фақат ортиқча жой ютилмайди.
   */
  fill?: boolean;
}

export function AreaPhoto({ src, alt, note, fill = true }: AreaPhotoProps) {
  const [st, setSt] = useState<"load" | "ok" | "fail">("load");

  return (
    <div
      className={
        "relative aspect-[16/10] w-full overflow-hidden rounded-card border border-grid bg-sunken" +
        (fill ? " grow" : "")
      }
    >
      {st !== "fail" && (
        <img
          src={src}
          alt={alt}
          loading="lazy"
          onLoad={() => setSt("ok")}
          onError={() => setSt("fail")}
          className={"h-full w-full object-cover" + (st === "ok" ? "" : " opacity-0")}
        />
      )}
      {st === "fail" && (
        <div className="absolute inset-0 flex flex-col items-center justify-center gap-1.5 px-5 text-center">
          <span aria-hidden="true" className="h-px w-10 bg-rule" />
          <span className="text-[12px] text-ink-2">Сурат юкланмаган</span>
          <span className="max-w-[42ch] text-[11px] leading-[1.45] text-ink-3">{note}</span>
        </div>
      )}
    </div>
  );
}
