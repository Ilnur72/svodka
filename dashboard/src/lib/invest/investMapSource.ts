/**
 * «Лойиҳалар харитаси» — лойиҳаларнинг координаталари ва ранг жадвали.
 *
 * Бу файлда фақат **манба** турибди: ҳар бир лойиҳанинг координатаси, ёрлиқ
 * томони ва лойиҳа тури → маркер ранги жадвали. Хаританинг ўзи (стил,
 * қатламлар, бошланғич кўриниш) `investMapStyle.ts` да, ҳисоб ва матн эса
 * `lib/adapters/investMap.ts` да.
 *
 * ═══ Координата — ТУМАН ДАРАЖАСИДАГИ ТАХМИН ═════════════════════════════
 *
 * Инвестиция реестрида координата майдони **умуман йўқ**: `investSource.ts`
 * даги ягона жой маълумоти — матнли ҳудуд номи («Тошкент вилояти Пискент
 * тумани»). Шунинг учун бу ердаги ҳар бир lon/lat — ўша туманнинг маркази
 * ёки кон ҳудуди, яъни тахмин. Хатоси бир неча километр бўлиши мумкин.
 *
 * Бу «харита аниқ эмас» дегани эмас — хаританинг ўзи ҳақиқий геодезик
 * асосда (EPSG:3857, OpenStreetMap маълумоти). Аниқ бўлмаган нарса — **шу
 * еттита нуқта**, чунки манбада улар йўқ. Шунинг учун экранда ҳар бир
 * маркер «тахминий жой» белгиси билан кўрсатилади ва харита ўлчов воситаси
 * сифатида ишлатилмайди: у «лойиҳа тахминан қаерда» саволига жавоб беради.
 *
 * Худди шу ёндашув `lib/geo/uzbekistan.ts` да ҳам: у ерда маркер вилоят
 * марказида туради ва бу лойиҳанинг ҲАҚИҚИЙ жойи эмаслиги очиқ айтилган.
 *
 * Фойдаланувчи маркерни ўзи суриб тўғрилай олади («Жойни тўғрилаш»
 * режими) — янги координата браузернинг ўзида сақланади ва манбага тегмайди.
 *
 * ═══ Устма-уст тушган маркерлар — силжиш КООРДИНАТА даражасида ══════════
 *
 * Лойиҳалар географик жиҳатдан зич: Оҳангарон ва Нуробод туманларида
 * иккитадан лойиҳа бор, туман маркази эса иккисига ҳам БИР ХИЛ нуқта
 * беради — маркерлар бир-бирини тўлиқ бекитарди.
 *
 * Ҳал қилиш усули: жуфтликнинг иккиси ҳам туман ИЧИДА қарама-қарши томонга
 * силжитилади (20–22 км). Сабаби `nudge` да ёзилади ва экранда кўрсатилади.
 *
 * ⚠️ Бир пайт бу силжиш MapLibre маркеридаги `offset` (ЭКРАН ПИКСЕЛИ) билан
 * берилган эди — ва бу нотўғри чиқди. Пиксел силжиш зум билан ўзгармайди,
 * иккита координата орасидаги ЭКРАН масофаси эса зум ошганда ортади:
 * натижада жуфтлик зум давомида бир-биридан ажралиб борарди, яъни маркер
 * ўз нуқтасидан «сузиб» кетарди. Фойдаланувчи буни аниқ кўрди — силжитилмаган
 * иккита лойиҳа (Мискон, Сульфат) жойида турган, қолгани зум пайтида
 * қимирлаган. Ўлчов билан текширилди: энди маркер ҳалқаси ҳар қандай зумда
 * ўз координатасидан **0,5 пикселдан** кўп четлашмайди.
 *
 * Шунинг учун бу файлда пиксел силжиш майдони УМУМАН ЙЎҚ ва қайта
 * киритилмайди. Эвазига паст зумда жуфтликнинг кристаллари бир-бирига
 * яқин туради — бу атайин қабул қилинган: ёрлиқлар `labelDy` билан
 * ажратилган ва иккови ҳам ўқилади, яқинлашилганда эса кристаллар ҳам
 * ажралади.
 *
 * ═══ Ёрлиқ: томони ва баландлиги ════════════════════════════════════════
 *
 * Ёрлиқ (лойиҳанинг қисқа номи) харитада **доим** кўринади, шунинг учун
 * унинг ўрни ҳам шу жадвалда — ҳисоблаб топилмайди. Иккита ростлагич бор:
 *
 *   · `label` — қайси ёнда. Қоида: ёрлиқ қўшнисидан қочади, яъни гуруҳнинг
 *     ғарбий чеккасидаги маркер чапга, қолгани ўнгга қарайди;
 *   · `labelDy` — вертикал силжиш, экран пикселида. Ёнма-ён турган иккита
 *     ёрлиқ бир хил баландликда бўлса кесишарди.
 *
 * Қийматлар ўйлаб топилмаган: улар headless браузерда `map.project()` билан
 * ўлчанган ҳақиқий экран координаталаридан ҳисобланган ва рендер қилиб
 * текширилган. Еттита нуқта учун қўлда текширилган жадвал энг ишончли усул —
 * `INVEST_KIND_COLOR` ва `geologyMap.ts` даги `REGION_KEYS` каби.
 */

