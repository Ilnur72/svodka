import { useState } from "react";

/**
 * «Лойиҳа майдони» блокидаги сурат майдони.
 *
 * ═══ «Сурат ЙЎҚ» ва «сурат ЮКЛАНМАДИ» — бошқа-бошқа ════════════════════
 *
 * Бу компонентнинг асосий вазифаси шу фарқни сақлаш:
 *
 *   · `src === null` — манбада бу лойиҳа учун сурат УМУМАН бириктирилмаган
 *     (реестрда `image` устуни `null`, 144 дан 100 тасида). Бу ҲАЛ ҚИЛИНГАН,
 *     маълум ҳолат — хато эмас, кутиш ҳам эмас. Сўров умуман юборилмайди;
 *   · `src` бор, лекин `onError` — манзил айтилган, файл эса КЕЛМАДИ:
 *     `public/` га қўйилмаган, деплойда тушиб қолган ёки номи мос эмас.
 *     Бу ҲАҚИҚИЙ носозлик ва у «сурат йўқ» билан аралашмаслиги керак —
 *     акс ҳолда йўқолган файл жимгина «нормал ҳолат» бўлиб қолиб кетарди.
 *
 * Шунинг учун иккаласининг сарлавҳа матни ҲАР ХИЛ, иккинчи қатори эса
 * чақирувчидан келади (`note` — юкланмаганда, `emptyNote` — сурат йўқлигида).
 * `null ≠ хато` — бўлим бўйлаб бир хил қоида (қаранг: `coordsStatus`,
 * `NO_DATA`).
 *
 * ═══ Файл бор-йўқлиги фақат браузерда маълум ════════════════════════════
 *
 * Файл `public/` да туради — у бандлга кирмайди, шунинг учун build
 * пайтида ҳам, рендер пайтида ҳам «бор ёки йўқ» деб текшириб бўлмайди.
 * Манзил берилганда ягона ишончли сигнал — браузернинг ўзи: `onLoad` ёки
 * `onError`.
 *
 * Тўртта ҳолат бор ва тўрттаси ҳам бошқача кўринади:
 *   - `none` — манзилнинг ўзи йўқ: `img` умуман чизилмайди (яъни 404 ҳам
 *     сўралмайди), ўрнида «сурат йўқ» плашкаси туради;
 *   - `load` — жавоб ҳали келмаган: жойни нейтрал майдон эгаллаб туради,
 *     расм эса шаффоф. Айнан шу сабабли синиқ расм иконкаси ҳам, `alt`
 *     матни ҳам экранга чиқмайди;
 *   - `ok`   — расм кўринади;
 *   - `fail` — расм умуман чизилмайди, ўрнида «юкланмаган» плашкаси туради.
 *
 * `aspect-[16/10]` — расмнинг энг кичик баландлиги, қатъий ўлчов эмас.
 *
 * ═══ Нега алоҳида компонент ═════════════════════════════════════════════
 *
 * Юқоридаги ҳолатлар иккита бўлимда бир хил керак: «Инвестиция
 * лойиҳалари» паспортида ва «Лойиҳалар реестри» тафсилотида. Иккинчи
 * нусхаси ёзилса, биттасида `onError` унутилиши билан ўша ерда синиқ расм
 * иконкаси пайдо бўларди. Блокнинг қолган қисми (сарлавҳа, кўрсаткичлар,
 * изоҳ) ҳар бўлимнинг ўзида қолади — улар манбага боғлиқ.
 */
export interface AreaPhotoProps {
  /**
   * Расмнинг тўлиқ манзили, ёки `null` — манбада сурат бириктирилмаган.
   *
   * ⚠️ `null` да `img` элементи умуман яратилмайди: йўқ файлга сўров юбориб,
   * консолни 404 билан тўлдириш — «маълумот йўқ» ни «носозлик» га
   * айлантириш дегани.
   */
  src: string | null;
  /** Расмнинг матнли муқобили — лойиҳа номи билан. */
  alt: string;
  /**
   * Плашканинг иккинчи қатори, расм ЮКЛАНМАГАНДА: манзил бор эди, лекин
   * файл келмади. Бўлимга қараб матн бошқача, шунинг учун чақирувчидан
   * келади.
   */
  note: string;
  /**
   * Плашканинг иккинчи қатори, сурат УМУМАН бириктирилмаганда (`src === null`).
   *
   * Берилмаса `note` ишлатилади — манзили доим ясаладиган бўлимлар учун
   * («Инвестиция лойиҳалари» паспорти: у ерда `src` ҳеч қачон `null` эмас,
   * яъни бу ҳолат юзага келмайди).
   */
  emptyNote?: string;
  /**
   * Устун грид қатори баландлигига чўзилганда ортиқча жойни расм ютсинми.
   *
   * `true` («Инвестиция лойиҳалари» паспорти) — ютади: у ерда уч устун
   * баландлиги яқин ва расм шу блокнинг асосий мазмуни, шунинг учун бўш
   * оралиқ ҳосил қилгандан кўра расмни каттароқ кўрсатган маъқул.
   *
   * `false` («Лойиҳалар реестри» тафсилоти) — ютмайди: у ерда чап устунда
   * тўрттагача карточка туради ва расм 700px дан ошиб кетарди. Реестрдаги
   * 144 лойиҳанинг 100 тасида сурат йўқ, яъни ўша жой бўм-бўш плашка бўлиб
   * қоларди. Нисбат ўзгармайди — фақат ортиқча жой ютилмайди.
   */
  fill?: boolean;
}

export function AreaPhoto({ src, alt, note, emptyNote, fill = true }: AreaPhotoProps) {
  const [st, setSt] = useState<"load" | "ok" | "fail">("load");

  // Манзил йўқлиги — юклаш ҳолатидан ТАШҚАРИДАГИ факт, шунинг учун у
  // `useState` да сақланмайди: `src` ўзгарса ҳолат ўз-ўзидан тўғри бўлади.
  const none = src === null;
  const plate = none || st === "fail";

  return (
    <div
      className={
        "relative aspect-[16/10] w-full overflow-hidden rounded-card border border-grid bg-sunken" +
        (fill ? " grow" : "")
      }
    >
      {!plate && (
        <img
          src={src}
          alt={alt}
          loading="lazy"
          onLoad={() => setSt("ok")}
          onError={() => setSt("fail")}
          className={"h-full w-full object-cover" + (st === "ok" ? "" : " opacity-0")}
        />
      )}
      {plate && (
        <div className="absolute inset-0 flex flex-col items-center justify-center gap-1.5 px-5 text-center">
          <span aria-hidden="true" className="h-px w-10 bg-rule" />
          <span className="text-[12px] text-ink-2">
            {none ? "Бу лойиҳа учун сурат йўқ" : "Сурат юкланмаган"}
          </span>
          <span className="max-w-[42ch] text-[11px] leading-[1.45] text-ink-3">
            {none ? (emptyNote ?? note) : note}
          </span>
        </div>
      )}
    </div>
  );
}
