/** Жуфтлик қандай далил билан ўрнатилган. */
export type RegistryScheduleProof =
  /** Иккала манбадаги лойиҳа қиймати мос тушди (энг кучли далил). */
  | "value"
  /** Реестрда шу номдаги лойиҳа ягона — бошқа номзод йўқ. */
  | "name"
  /** Фойдаланувчи қайси босқич эканини кўрсатган. */
  | "user"
  /** Мустақил далил йўқ — тасдиқланмаган тахмин. */
  | "assumed";

export interface RegistryScheduleLink {
  /**
   * Реестрдаги лойиҳа `key` — МОСЛИК ФАҚАТ ШУ ЁЗУВНИНГ ТЎЛИҚ ТЕНГЛИГИ
   * бўйича. Қисман мослик, кичик ҳарфга келтириш, hash қисмини ташлаб
   * юбориш — ҳеч қайсиси йўқ.
   */
  registryKey: string;
  /** Базадаги id — фақат изоҳ ва огоҳлантириш матни учун. */
  registryId: number;
  /** `/project-schedule/dashboard` жавобидаги `projects[].key`. */
  scheduleKey: string;
  proof: RegistryScheduleProof;
  /** Далилнинг ўқиладиган матни — ойнада очиқ кўрсатилади. */
  proofText: string;
}

